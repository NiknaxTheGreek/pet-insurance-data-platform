USE ROLE SNOWFLAKE_LEARNING_ROLE;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;
USE DATABASE SNOWFLAKE_LEARNING_DB;

DROP SCHEMA IF EXISTS PET_INSURANCE_BENCHMARK;
CREATE SCHEMA PET_INSURANCE_BENCHMARK;

CREATE TABLE PET_INSURANCE_BENCHMARK.SOURCE_RECORDS (
  RAW_RECORD_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
  SOURCE_TABLE VARCHAR NOT NULL,
  SOURCE_PK VARCHAR NOT NULL,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  OPERATION VARCHAR NOT NULL,
  PAYLOAD VARIANT NOT NULL,
  PAYLOAD_HASH VARCHAR(64) NOT NULL,
  BATCH_ID VARCHAR NOT NULL,
  INGESTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE PET_INSURANCE_BENCHMARK.INGESTION_WATERMARKS (
  SOURCE_TABLE VARCHAR PRIMARY KEY,
  LAST_UPDATED_AT TIMESTAMP_TZ,
  LAST_SOURCE_PK VARCHAR,
  UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE PET_INSURANCE_BENCHMARK.INGESTION_BATCHES (
  BATCH_ID VARCHAR PRIMARY KEY,
  SOURCE_TABLE VARCHAR,
  STARTED_AT TIMESTAMP_TZ NOT NULL,
  COMPLETED_AT TIMESTAMP_TZ,
  STATUS VARCHAR NOT NULL,
  SOURCE_ROWS NUMBER,
  ROWS_EXTRACTED NUMBER NOT NULL DEFAULT 0,
  ROWS_INSERTED NUMBER NOT NULL DEFAULT 0,
  WATERMARK_BEFORE_AT TIMESTAMP_TZ,
  WATERMARK_BEFORE_PK VARCHAR,
  WATERMARK_AFTER_AT TIMESTAMP_TZ,
  WATERMARK_AFTER_PK VARCHAR,
  DURATION_MS NUMBER,
  RETRY_COUNT NUMBER NOT NULL DEFAULT 0,
  RECONCILIATION_STATUS VARCHAR,
  ERROR_CLASS VARCHAR,
  ERROR_MESSAGE VARCHAR,
  GITHUB_RUN_ID VARCHAR,
  NOTES VARCHAR
);

CREATE TABLE PET_INSURANCE_BENCHMARK.INGESTION_STAGE (
  BATCH_ID VARCHAR NOT NULL,
  SOURCE_TABLE VARCHAR NOT NULL,
  SOURCE_PK VARCHAR NOT NULL,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  OPERATION VARCHAR NOT NULL,
  PAYLOAD_JSON VARCHAR NOT NULL,
  PAYLOAD_HASH VARCHAR(64) NOT NULL,
  STAGED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);
